"""Книги и авторы, которых нет в продаже в России: запреты, перечни, снятые с продажи и изъятые издательствами.
Тот же список, что в app-dev.html (BAN_AU, BAN_T). Используется сборщиками каталога и страниц сайта."""
import re
BAN_AU = {"акунин", "глуховский", "быков|д", "улицкая", "шишкин|м", "горалик", "шендерович", "малисова", "сильванова", "янагихара", "асиман",
          "осман|э", "макквинстон", "макквистон", "евгенидис", "уэлш", "берроуз|у", "эберсхофф", "жижек", "гитлер"}
BAN_T = {t.replace("ё", "е") for t in ["лето в пионерском галстуке", "о чем молчит ласточка", "девушка из дании", "маленькая жизнь", "до самого рая",
         "песнь ахилла", "назови меня своим именем", "сердцеед", "heartstopper", "красный белый и королевский синий", "средний пол", "на игле",
         "голый завтрак", "квир", "джанки", "майн кампф", "комната джованни", "одинокий мужчина", "морис", "почти прозрачный голубой",
         "все оттенки голубого", "ночь когда мы исчезли", "табия тридцать два", "закрытые жизнь гомосексуалов в ссср", "исповедь маски"]}
def _n(s): return re.sub(r"[^a-zа-я0-9]+", " ", str(s or "").lower().replace("ё", "е")).strip()
def is_ban(t, a):
    t = _n(t)
    if t in BAN_T or any(len(x) > 9 and t.startswith(x + " ") for x in BAN_T): return True
    w = _n(a).split()
    if not w: return False
    return w[-1] in BAN_AU or (w[-1] + "|" + w[0][0]) in BAN_AU
